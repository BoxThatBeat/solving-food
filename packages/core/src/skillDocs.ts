// Generated sections of the Claude skill (.claude/skills/solving-food-skill/references/), rendered from the same lists
// the importer validates against. Used by `pnpm gen:skill` and checked by skill.test.ts.
import { TOOL_SYNONYMS } from "./tools";
import { CUISINES, MAIN_PROTEINS } from "./taxonomy";
import { UNITS } from "./units";
import { INGREDIENT_CATEGORIES, PREP_WORDS, SPELLING_VARIANTS, STATE_WORDS } from "./ingredient";

const HEADER = "<!-- Generated by `pnpm gen:skill` from packages/core. Do not edit by hand. -->\n\n";

export function renderTaxonomy(): string {
  const units = (kind: string) =>
    Object.values(UNITS)
      .filter((u) => u.kind === kind && u.key !== "count")
      .map((u) => `\`${u.key}\``)
      .join(", ");
  return `${HEADER}# Fixed lists

The importer rejects any other value (case and spaces are forgiven: \`Middle Eastern\` → \`middle-eastern\`).

## cuisine

${CUISINES.map((c) => `- \`${c}\``).join("\n")}

Pick the closest; \`other\` only when nothing fits. Moroccan and Lebanese are \`middle-eastern\`; Tex-Mex is \`mexican\`;
a generic North American bake or casserole is \`american\`.

## main_protein

${MAIN_PROTEINS.map((p) => `- \`${p}\``).join("\n")}

The protein the dish is built around. Ham, bacon, sausage are \`pork\`; shrimp and shellfish are \`seafood\`; beans,
lentils, chickpeas, peanut butter are \`legumes\`; cheese- or yogurt-led dishes are \`dairy\`; egg-led bakes are \`eggs\`;
sweets and plain sides are \`none\`.

## Units the app converts

- Weight: ${units("weight")}
- Volume: ${units("volume")}
- Vague (no amount tracked): ${units("vague")}
- Anything else is a count noun: \`@egg{2}\`, \`@garlic{3%cloves}\`, \`@lemon{1}\`. Common spellings work too
  (\`Tbsp\`, \`teaspoons\`, \`lbs\`, \`T\` = tablespoon).

## Cookware names

Write \`#cookware{}\` with the plain canonical name, lower-case, no size: \`#skillet{}\`, not \`#large frying pan{}\` or
\`#10-inch skillet{}\`; \`#baking dish{}\`, not \`#9x13-inch pan{}\`. Put a size that matters in the step text ("a
9x13-inch #baking dish{}"). The app matches kitchen tools by these names; the other spellings on each line still match,
but the canonical one keeps the library tidy.

${Object.entries(TOOL_SYNONYMS)
  .map(([canon, alts]) => `- \`${canon}\`${alts.length ? ` (not ${alts.map((a) => `"${a}"`).join(", ")})` : ""}`)
  .join("\n")}

Tools not listed here: the plain singular name (\`#wok{}\`, \`#rolling pin{}\`, \`#oven{}\`).
`;
}

interface NamedIngredient {
  name: string;
  aliases: string[];
  category: string;
}

export function renderIngredients(items: readonly NamedIngredient[]): string {
  const sections = INGREDIENT_CATEGORIES.map((cat) => {
    const list = items.filter((i) => i.category === cat).sort((a, b) => a.name.localeCompare(b.name));
    if (!list.length) return "";
    const lines = list.map((i) => `- ${i.name}${i.aliases.length ? ` (${i.aliases.join(", ")})` : ""}`);
    return `## ${cat}\n\n${lines.join("\n")}\n`;
  }).filter(Boolean);
  const code = (l: readonly string[]) => l.map((w) => `\`${w}\``).join(", ");
  return `${HEADER}# Ingredient names the app already knows

${items.length} ingredients. **Every \`@ingredient{}\` token must be one of these names or an alias in brackets**
whenever one means the same thing (SKILL.md step 6 checks this before delivery). The importer matches names and aliases
ignoring case, accents, punctuation and plurals, folds the spelling variants below, and drops preparation words, but
write the catalogue name anyway: the token is what the recipe shows and what the next person searches for.

A name that matches nothing creates a **new ingredient flagged for review**: its lines don't reduce the household's
Supply and its grocery lines don't merge until someone merges it into the right ingredient in the app. Use a new name
only when nothing here means the same thing, and list it in the delivery message with a one-line reason.

## Preparation words go outside the token

These describe what the cook does, not what is bought. Write them after the token, never inside it:
\`@chicken thigh{2%lb}, boneless, diced\`, \`@butter{2%tbsp}, softened\`, \`@cilantro{}, chopped, for serving\`.

${code(PREP_WORDS)}

These change what is bought, so keep them in the token only when the catalogue has that form (\`@frozen peas{}\`,
\`@ground cumin{}\`, \`@dried oregano{}\`, \`@canned black beans{}\`); otherwise use the plain name and put the word
outside: ${code(STATE_WORDS)}.

## Spelling variants

The importer treats each line's spellings as the same word. These are spellings, not catalogue entries: the
ingredient itself must still be in the list below (green chiles and m&ms aren't, yet). Write the spelling the list uses:

${SPELLING_VARIANTS.map(([canon, others]) => `- ${canon} (${others.join(", ")})`).join("\n")}

${sections.join("\n")}`;
}
