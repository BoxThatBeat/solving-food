// Adding a recipe with Gemini (PRD R4.37; TECHNICAL_SPECS §9 "Add with Gemini", Planning/M16): pure helpers. The prompt
// is the Claude skill itself (rendered into functions/src/ai/skillText.generated.ts by `pnpm gen:skill`, one source of
// truth); a web page is reduced to its schema.org Recipe JSON-LD, or else its visible text; Gemini's answer is read for
// the .cook file. The file then goes through the drop-folder importer like any other.

/** The skill files that make up the prompt, in order (the delivery reference is left out: the app delivers). */
export const SKILL_PROMPT_FILES = ["SKILL.md", "references/syntax.md", "references/conventions.md", "references/taxonomy.md", "references/ingredients.md"] as const;

/** The generated module's text: each skill file under its path. */
export function renderSkillPrompt(files: Readonly<Record<(typeof SKILL_PROMPT_FILES)[number], string>>): string {
  return SKILL_PROMPT_FILES.map((f) => `===== ${f} =====\n${files[f].trim()}\n`).join("\n");
}

/** The generated TypeScript module (functions/src/ai/skillText.generated.ts). */
export function renderSkillModule(files: Readonly<Record<(typeof SKILL_PROMPT_FILES)[number], string>>): string {
  return `// Generated by \`pnpm gen:skill\` from .claude/skills/solving-food-skill/ (M16): the skill Gemini follows to write a\n// .cook file. Don't edit; change the skill and regenerate.\nexport const SKILL_TEXT = ${JSON.stringify(renderSkillPrompt(files))};\n`;
}

export type RecipeSource = { kind: "link"; url: string } | { kind: "photo" };

/** The system instruction: the app's framing, then the skill. */
export function recipeInstruction(skillText: string, source: RecipeSource): string {
  const where =
    source.kind === "link"
      ? `The recipe comes from the web page ${source.url}; its content is given below (schema.org data or the page's text). Use ${source.url} as \`source\`, and the recipe's own image URL as \`image\` when the page gives one (a direct image URL, never a page).`
      : "The recipe comes from the attached photo of a cookbook page or recipe card. Read every ingredient and step from it. Leave out `source` and `image`: the photo is not the recipe's picture.";
  return `You add recipes to the Solving Food app by writing a Cooklang .cook file. Follow the skill below exactly: its steps 1 to 7 and every rule, the front matter keys, the ingredient names from its list, the units. Skip its delivery step: the app imports your file itself, so there is no drop folder, gcloud, or delivery message.
${where}
If the content isn't a recipe, answer only: NOT A RECIPE.
Otherwise answer with only the .cook file inside one \`\`\`cooklang code block, nothing before or after it.

${skillText}`;
}

/** The .cook file in Gemini's answer: a ```cooklang (or ```cook) block, else the text from its front matter on. */
export function extractCook(answer: string): string | null {
  const fence = /```(?:cooklang|cook)?[^\n]*\n([\s\S]*?)```/i.exec(answer);
  const body = (fence ? fence[1]! : answer.slice(Math.max(0, answer.indexOf("---")))).trim();
  if (!body.startsWith("---") || !/\n---\s*\n/.test(body.slice(3) + "\n")) return null;
  return `${body}\n`;
}

/** Whether Gemini said the content isn't a recipe. */
export function notARecipe(answer: string): boolean {
  return /^\s*NOT A RECIPE\b/i.test(answer);
}

/** Drops an `image:` front matter line that isn't an http(s) URL (a photo import has no picture to upload). */
export function dropLocalImage(cook: string): string {
  return cook.replace(/^image:[ \t]*(?!https?:\/\/)\S.*\n/im, "");
}

type J = Record<string, unknown>;
const isRecipe = (n: unknown): n is J => {
  const t = (n as J | null)?.["@type"];
  return Array.isArray(t) ? t.includes("Recipe") : t === "Recipe";
};

function findRecipe(node: unknown, depth = 0): J | null {
  if (!node || typeof node !== "object" || depth > 6) return null;
  if (Array.isArray(node)) {
    for (const x of node) {
      const r = findRecipe(x, depth + 1);
      if (r) return r;
    }
    return null;
  }
  if (isRecipe(node)) return node;
  const o = node as J;
  return findRecipe(o["@graph"], depth + 1) ?? findRecipe(o.mainEntity, depth + 1);
}

/** The page's schema.org Recipe (JSON-LD), or null. */
export function extractRecipeJsonLd(html: string): J | null {
  for (const m of html.matchAll(/<script[^>]*type\s*=\s*["']?application\/ld\+json["']?[^>]*>([\s\S]*?)<\/script>/gi)) {
    try {
      const r = findRecipe(JSON.parse(m[1]!.trim()));
      if (r) return r;
    } catch {
      // a broken block: try the next one
    }
  }
  return null;
}

const ENTITIES: Record<string, string> = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", frac12: "½", frac14: "¼", frac34: "¾", deg: "°" };

/** The page's visible text: scripts, styles and tags dropped, block tags as line breaks, whitespace collapsed. */
export function htmlToText(html: string, max = 30_000): string {
  return html
    .replace(/<(script|style|noscript|svg|head|nav|footer|iframe)[\s\S]*?<\/\1>/gi, " ")
    .replace(/<\/?(p|div|li|ul|ol|h[1-6]|br|tr|section|article|header)[^>]*>/gi, "\n")
    .replace(/<[^>]+>/g, " ")
    .replace(/&(#\d+|#x[0-9a-f]+|\w+);/gi, (all, e: string) => {
      if (e[0] === "#") return String.fromCodePoint(e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : Number(e.slice(1)));
      return ENTITIES[e.toLowerCase()] ?? all;
    })
    .replace(/[ \t\f\v\r]+/g, " ")
    .replace(/\n\s*\n+/g, "\n")
    .trim()
    .slice(0, max);
}

/** What Gemini is told about a page: its Recipe JSON-LD when it has one, else its text. Null when there's next to nothing. */
export function pageContent(url: string, html: string): string | null {
  const ld = extractRecipeJsonLd(html);
  if (ld) return `Recipe data (schema.org JSON-LD) from ${url}:\n${JSON.stringify(ld).slice(0, 40_000)}`;
  const text = htmlToText(html);
  return text.length < 200 ? null : `Text of the page ${url}:\n${text}`;
}

/** An http(s) URL that isn't this machine or a private network (the function fetches it). Null when refused. */
export function safeRecipeUrl(raw: string): URL | null {
  let u: URL;
  try {
    u = new URL(raw.trim());
  } catch {
    return null;
  }
  if (u.protocol !== "https:" && u.protocol !== "http:") return null;
  const h = u.hostname.toLowerCase().replace(/^\[|\]$/g, "");
  if (!h.includes(".") || h === "localhost" || h.endsWith(".local") || h.endsWith(".internal") || h === "metadata.google.internal") return null;
  if (/^(127\.|10\.|192\.168\.|169\.254\.|0\.|172\.(1[6-9]|2\d|3[01])\.)/.test(h) || h.includes(":")) return null;
  return u;
}
